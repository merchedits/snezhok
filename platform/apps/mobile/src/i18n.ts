export type TranslationKey = keyof typeof en;
export type Language = AppSettings["language"];

export function translate(language: Language, key: TranslationKey, values?: Record<string, string | number>): string {
  const template = (language === "ru" ? ru : en)[key];
  if (!values) return template;
  return Object.entries(values).reduce((text, [name, value]) => text.replaceAll(`{${name}}`, String(value)), template);
}

export function useTranslation() {
  const language = useAppStore((state) => state.settings.language);
  const t = useCallback((key: TranslationKey, values?: Record<string, string | number>) => translate(language, key, values), [language]);
  return { language, t };
}

export function optionLabel(language: Language, value: string): string {
  const keys: Partial<Record<string, TranslationKey>> = {
    system: "system", light: "light", dark: "dark", blue: "blue", green: "green", purple: "purple", orange: "orange", red: "red",
    "data-saver": "dataSaver", auto: "auto", high: "high", original: "original", off: "off", standard: "standard",
  };
  const key = keys[value];
  return key ? translate(language, key) : value;
}
